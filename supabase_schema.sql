CREATE INDEX IF NOT EXISTS idx_usuarios_correo ON public.usuarios(correo);
CREATE INDEX IF NOT EXISTS idx_usuarios_rol_id ON public.usuarios(rol_id);

-- =============================================================================
-- 3. TABLA: products
-- Basada en ProductEntity.kt y ProductRepositoryImpl.kt
-- Nota: imageurl y createdat van sin guion bajo por @SerialName en Kotlin
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text DEFAULT '',
    description text DEFAULT '',
    category text DEFAULT 'Pasteles',
    price double precision DEFAULT 0.0,
    stock integer DEFAULT 0,
    status text DEFAULT 'Activo',
    imageurl text,
    createdat timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);
CREATE INDEX IF NOT EXISTS idx_products_name ON public.products(name);

-- Trigger para evitar conflictos si el cliente envía id = 0 o NULL al insertar
CREATE OR REPLACE FUNCTION public.handle_zero_id_products()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
    IF NEW.id IS NULL OR NEW.id = 0 THEN
        NEW.id := nextval(pg_get_serial_sequence('public.products', 'id'));
    END IF;
    IF NEW.createdat IS NULL THEN
        NEW.createdat := now();
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_products_zero_id ON public.products;
CREATE TRIGGER trg_products_zero_id
BEFORE INSERT ON public.products
FOR EACH ROW
EXECUTE FUNCTION public.handle_zero_id_products();

